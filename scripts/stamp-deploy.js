// Vercel runs this as the build command (see vercel.json). It records when
// the site was deployed, for the hub's "updated" line. deployed.js is
// generated, not committed; without it pages fall back to the current month.
import { writeFileSync } from "node:fs";

const at = new Date().toISOString();
writeFileSync(
  new URL("../deployed.js", import.meta.url),
  `// Generated by scripts/stamp-deploy.js at build time.\nglobalThis.DEPLOYED = "${at}";\n`,
);
console.log("deployed.js stamped", at);
